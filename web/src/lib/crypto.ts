/**
 * Certificate helpers. Kept out of the API client so networking stays pure.
 *
 * `crypto.subtle` is only available in a secure context (HTTPS or localhost).
 * Accessing the Docker UI via `http://<lan-ip>:port` makes it `undefined`, so
 * hashing falls back to a pure SHA-256 implementation.
 */

